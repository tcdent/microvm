//! Golden filesystem caches.
//!
//! Two flat, immutable-after-init, `Arc`-shareable caches populated
//! from S3 at orchestrator startup (research/12 §3):
//!
//! - [`GoldenInodeCache`] — path → `GoldenEntry` (hash, mode, owner,
//!   size, optional symlink target). Serves FUSE `lookup` / `getattr`
//!   on golden-inherited paths without ever hitting S3 after init.
//! - [`GoldenBlobCache`] — hash → `Arc<Vec<u8>>`. Every blob under
//!   `golden/<hash>` pinned in RAM. Serves FUSE `read` on golden-
//!   inherited regular files at memcpy speed.
//!
//! Both are populated once by [`load_golden`] and then handed out as
//! `Arc<_>`s to every per-VM `S3Fs` the orchestrator constructs. No
//! `Mutex`, no TTL, no eviction — the working set is bounded by the
//! golden rootfs (~120 MB today), fits comfortably in host RAM, and
//! is immutable for the orchestrator's lifetime.
//!
//! # History
//!
//! A tiered cache (RAM + disk + S3 fallback) with LFU eviction lived
//! here briefly (commit `586c815`) on the assumption that memory
//! pressure on content-addressed data would eventually demand it. The
//! tiered design was removed when `research/12` settled on pinning
//! the entire bounded golden pool in RAM — the simpler design matches
//! the actual workload. The rotating-offset probabilistic sampling
//! pattern is preserved in git history at `586c815` for any future
//! workload that does need bounded-memory eviction.

use std::collections::HashMap;
use std::io;
use std::sync::Arc;

use rayon::prelude::*;
use serde::{Deserialize, Serialize};

use crate::config::{GoldenConfig, ManifestSource};
use crate::s3::{S3Client, S3ResultExt};

// ── Manifest: on-wire format ───────────────────────────────────────────

/// Bincode-encoded description of a golden rootfs. Generated by the
/// bootstrap pipeline (Phase 8), consumed by [`load_golden`] at
/// orchestrator startup.
///
/// Versioned: a bump on `schema_version` signals a breaking wire
/// change and [`load_golden`] errors out rather than coerce. We lean
/// on explicit version checks rather than bincode's structural
/// tolerance because silently reading a differently-shaped manifest
/// is worse than a clear failure mode. Bump to `2` when (and only
/// when) the wire format actually changes.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct GoldenManifest {
    pub schema_version: u32,
    pub entries: Vec<GoldenManifestEntry>,
}

/// Per-path description in the manifest. Covers regular files
/// (`hash = Some(_)`), directories and symlinks (`hash = None`).
///
/// Symlink targets live inline on the entry — the manifest is the
/// single source of truth for every non-blob-bearing bit of the
/// golden rootfs. Putting targets here means a golden symlink costs
/// zero S3 GETs at init (vs one per symlink if we stored targets as
/// blob bodies), saving ~100 × ~5ms on a typical Debian base layer.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct GoldenManifestEntry {
    pub path: String,
    /// Content hash of the blob at `golden/<hash>`. `None` for
    /// directories (metadata-only) and symlinks (target lives in
    /// `symlink_target`).
    pub hash: Option<String>,
    pub mode: u32,
    pub uid: u32,
    pub gid: u32,
    pub size: u64,
    /// Set for symlinks only. Ignored for other file types.
    pub symlink_target: Option<String>,
}

pub const GOLDEN_SCHEMA_VERSION: u32 = 1;

// ── In-memory caches ───────────────────────────────────────────────────

/// Per-path metadata for a golden-inherited inode. Mirrors
/// [`GoldenManifestEntry`] minus the wire-format annotations; kept
/// separate so the in-memory shape can diverge from the serialized
/// one (e.g. add computed fields) without breaking the manifest
/// format.
#[derive(Debug, Clone)]
pub struct GoldenEntry {
    /// Content hash for blob-bearing files; `None` for directories
    /// and symlinks. Symlink targets are served inline from
    /// `symlink_target` — they do NOT need a blob lookup.
    pub hash: Option<String>,
    pub mode: u32,
    pub uid: u32,
    pub gid: u32,
    pub size: u64,
    pub symlink_target: Option<String>,
}

/// Immutable, lock-free, `Arc`-shareable path → [`GoldenEntry`] cache.
/// Populated once at orchestrator init; never mutated after.
#[derive(Debug)]
pub struct GoldenInodeCache {
    by_path: HashMap<String, GoldenEntry>,
}

impl GoldenInodeCache {
    pub fn get(&self, path: &str) -> Option<&GoldenEntry> {
        self.by_path.get(path)
    }

    pub fn len(&self) -> usize {
        self.by_path.len()
    }

    pub fn is_empty(&self) -> bool {
        self.by_path.is_empty()
    }
}

/// Immutable, lock-free, `Arc`-shareable hash → bytes cache.
/// Populated once at orchestrator init from bulk S3 GETs; never
/// mutated after. `Arc<Vec<u8>>` payloads mean FUSE `read` gives out
/// byte views without copying.
#[derive(Debug)]
pub struct GoldenBlobCache {
    blobs: HashMap<String, Arc<Vec<u8>>>,
}

impl GoldenBlobCache {
    pub fn fetch(&self, hash: &str) -> Option<Arc<Vec<u8>>> {
        self.blobs.get(hash).map(Arc::clone)
    }

    pub fn len(&self) -> usize {
        self.blobs.len()
    }

    pub fn is_empty(&self) -> bool {
        self.blobs.is_empty()
    }

    /// Total bytes resident across all blobs. For observability.
    pub fn total_bytes(&self) -> usize {
        self.blobs.values().map(|b| b.len()).sum()
    }
}

// ── Loader ─────────────────────────────────────────────────────────────

/// Load the golden inode and blob caches into RAM.
///
/// Takes an [`S3Client`] and uses its bucket-override methods
/// (`get_from`) to pull against the golden bucket while reusing the
/// caller's credentials, endpoint, region, and connection pool. The
/// client's primary bucket is ignored here — this loader talks only
/// to `cfg.bucket`.
///
/// Flow:
/// 1. Fetch the manifest per [`ManifestSource`] (either `get_from`
///    the golden bucket or read from a local path).
/// 2. Bincode-deserialize into [`GoldenManifest`]. Fail if
///    `schema_version` doesn't match [`GOLDEN_SCHEMA_VERSION`].
/// 3. Build [`GoldenInodeCache`] by iterating manifest entries.
/// 4. Collect unique content hashes, bulk-fetch each from
///    `<golden-bucket>/<hash>` via rayon workers sharing `&client`,
///    assemble [`GoldenBlobCache`].
/// 5. Wrap both in `Arc`s.
///
/// Returns `Err` if the manifest can't be read / parsed, schema
/// version mismatches, or any blob fetch fails — a partial cache is
/// worse than no cache (per research/12 §6 a missing golden blob at
/// read time is treated as an invariant violation, so the loader
/// must guarantee the blob pool matches the manifest).
pub fn load_golden(
    cfg: &GoldenConfig,
    client: &S3Client,
) -> io::Result<(Arc<GoldenInodeCache>, Arc<GoldenBlobCache>)> {
    // Step 1: fetch manifest bytes.
    let manifest_bytes = fetch_manifest_bytes(&cfg.manifest, &cfg.bucket, client)?;

    // Step 2: bincode decode + schema check.
    // NOTE: the manifest is a trusted input — we control the golden
    // bucket and the bootstrap pipeline that writes it. No untrusted
    // deserialization concerns here. If the trust boundary ever
    // moves (e.g. golden served from a user-writable location), this
    // is the line that needs revisiting.
    let manifest: GoldenManifest = bincode::deserialize(&manifest_bytes).map_err(|e| {
        io::Error::new(
            io::ErrorKind::InvalidData,
            format!("golden manifest deserialize: {e}"),
        )
    })?;
    if manifest.schema_version != GOLDEN_SCHEMA_VERSION {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            format!(
                "golden manifest schema_version={} not supported (expected {})",
                manifest.schema_version, GOLDEN_SCHEMA_VERSION
            ),
        ));
    }

    // Step 3: inode cache. Straight map from manifest entries.
    let mut by_path: HashMap<String, GoldenEntry> = HashMap::with_capacity(manifest.entries.len());
    for e in &manifest.entries {
        by_path.insert(
            e.path.clone(),
            GoldenEntry {
                hash: e.hash.clone(),
                mode: e.mode,
                uid: e.uid,
                gid: e.gid,
                size: e.size,
                symlink_target: e.symlink_target.clone(),
            },
        );
    }
    let inodes = GoldenInodeCache { by_path };

    // Step 4: deduplicate hashes first, then par_iter the GETs. The
    // dedup-first shape means no lock contention during the fetch —
    // each unique hash is fetched exactly once, regardless of how
    // many paths reference it.
    let mut unique_hashes: Vec<String> = manifest
        .entries
        .iter()
        .filter_map(|e| e.hash.clone())
        .collect();
    unique_hashes.sort();
    unique_hashes.dedup();

    let blobs = if unique_hashes.is_empty() {
        // Empty manifest (or all dirs/symlinks) — skip the par_iter
        // entirely. rayon handles empty input fine but we can avoid
        // spinning up a pool we don't need.
        HashMap::new()
    } else {
        fetch_blobs_parallel(&unique_hashes, &cfg.bucket, client)?
    };

    let blob_cache = GoldenBlobCache { blobs };

    Ok((Arc::new(inodes), Arc::new(blob_cache)))
}

/// Fetch manifest bytes from either S3 or the local filesystem.
fn fetch_manifest_bytes(
    source: &ManifestSource,
    golden_bucket: &str,
    client: &S3Client,
) -> io::Result<Vec<u8>> {
    match source {
        ManifestSource::LocalPath(p) => std::fs::read(p).map_err(|e| {
            io::Error::new(e.kind(), format!("read golden manifest from {p:?}: {e}"))
        }),
        ManifestSource::S3Key(key) => client
            .get_from(golden_bucket, key)
            .io_err(&format!("golden manifest GET {}", key)),
    }
}

/// Bulk-fetch every unique blob hash in parallel via rayon.
///
/// Uses a **local** rayon `ThreadPool` via `.install(...)` rather than
/// `build_global()`. The library-vs-binary distinction matters: a
/// library that configures the global pool can't safely coexist with
/// other rayon consumers in the same process (build_global panics on
/// the second call). A local pool sized by
/// `available_parallelism().min(16)` costs ~1 ms to spawn and doesn't
/// touch global state.
///
/// All workers share the one `&S3Client` — `S3Client` is `Sync`, and
/// the `ureq::Agent` inside is built for concurrent use. No per-worker
/// client construction, no thread-local anything.
fn fetch_blobs_parallel(
    hashes: &[String],
    golden_bucket: &str,
    client: &S3Client,
) -> io::Result<HashMap<String, Arc<Vec<u8>>>> {
    let n_threads = std::thread::available_parallelism()
        .map(|n| n.get())
        .unwrap_or(8)
        .min(16);
    let pool = rayon::ThreadPoolBuilder::new()
        .num_threads(n_threads)
        .thread_name(|i| format!("golden-fetch-{i}"))
        .build()
        .map_err(|e| io::Error::new(io::ErrorKind::Other, format!("rayon pool build: {e}")))?;

    pool.install(|| {
        hashes
            .par_iter()
            .map(|hash| -> io::Result<(String, Arc<Vec<u8>>)> {
                let bytes = client
                    .get_from(golden_bucket, hash)
                    .io_err(&format!("golden GET {}", hash))?;
                Ok((hash.clone(), Arc::new(bytes)))
            })
            // Collect into Result — short-circuits on the first Err,
            // which matches the "abort on any fetch failure" policy.
            .collect::<io::Result<HashMap<_, _>>>()
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    fn entry(path: &str, hash: Option<&str>, mode: u32) -> GoldenManifestEntry {
        GoldenManifestEntry {
            path: path.to_string(),
            hash: hash.map(|s| s.to_string()),
            mode,
            uid: 0,
            gid: 0,
            size: 0,
            symlink_target: None,
        }
    }

    #[test]
    fn manifest_bincode_roundtrip() {
        let m = GoldenManifest {
            schema_version: GOLDEN_SCHEMA_VERSION,
            entries: vec![
                entry("usr/bin/bash", Some("aabbccdd"), libc::S_IFREG as u32 | 0o755),
                entry("etc", None, libc::S_IFDIR as u32 | 0o755),
                GoldenManifestEntry {
                    path: "bin".to_string(),
                    hash: None,
                    mode: libc::S_IFLNK as u32 | 0o777,
                    uid: 0,
                    gid: 0,
                    size: 7,
                    symlink_target: Some("usr/bin".to_string()),
                },
            ],
        };
        let encoded = bincode::serialize(&m).unwrap();
        let decoded: GoldenManifest = bincode::deserialize(&encoded).unwrap();
        assert_eq!(m, decoded);
    }

    #[test]
    fn inode_cache_get() {
        let mut by_path = HashMap::new();
        by_path.insert(
            "usr/bin/bash".to_string(),
            GoldenEntry {
                hash: Some("abc".to_string()),
                mode: libc::S_IFREG as u32 | 0o755,
                uid: 0,
                gid: 0,
                size: 1000,
                symlink_target: None,
            },
        );
        let cache = GoldenInodeCache { by_path };
        let hit = cache.get("usr/bin/bash").unwrap();
        assert_eq!(hit.hash.as_deref(), Some("abc"));
        assert_eq!(hit.size, 1000);
        assert!(cache.get("missing").is_none());
    }

    #[test]
    fn blob_cache_fetch_hit_and_miss() {
        let mut blobs = HashMap::new();
        blobs.insert("hash1".to_string(), Arc::new(b"bytes1".to_vec()));
        let cache = GoldenBlobCache { blobs };

        let hit = cache.fetch("hash1").unwrap();
        assert_eq!(&**hit, b"bytes1");
        assert!(cache.fetch("nope").is_none());
        assert_eq!(cache.total_bytes(), 6);
    }

    #[test]
    fn blob_cache_arc_shares_payload() {
        let mut blobs = HashMap::new();
        let original = Arc::new(vec![42u8; 1024]);
        blobs.insert("h".to_string(), Arc::clone(&original));
        let cache = GoldenBlobCache { blobs };

        let a = cache.fetch("h").unwrap();
        let b = cache.fetch("h").unwrap();
        // Three references: original, the cache's HashMap slot, a,
        // and b = 4 strong_count.
        assert_eq!(Arc::strong_count(&original), 4);
        // Two separate fetches hand out the same underlying payload,
        // not copies.
        assert!(Arc::ptr_eq(&a, &b));
    }

    #[test]
    fn load_from_local_manifest_metadata_only() {
        // Manifest with NO blob-bearing entries (all directories).
        // load_golden skips the bulk S3 fetch entirely since there
        // are no unique hashes to fetch.
        let tmp = tempfile::tempdir().unwrap();
        let manifest_path = tmp.path().join("manifest.bin");

        let m = GoldenManifest {
            schema_version: GOLDEN_SCHEMA_VERSION,
            entries: vec![
                entry("etc", None, libc::S_IFDIR as u32 | 0o755),
                entry("usr", None, libc::S_IFDIR as u32 | 0o755),
            ],
        };
        std::fs::write(&manifest_path, bincode::serialize(&m).unwrap()).unwrap();

        let cfg = GoldenConfig {
            bucket: "unused".to_string(),
            manifest: ManifestSource::LocalPath(manifest_path),
        };
        let client = S3Client::new(crate::s3::S3Config::default());

        let (inodes, blobs) = load_golden(&cfg, &client).unwrap();
        assert_eq!(inodes.len(), 2);
        assert!(inodes.get("etc").is_some());
        assert!(blobs.is_empty());
    }

    #[test]
    fn load_empty_manifest_succeeds() {
        let tmp = tempfile::tempdir().unwrap();
        let manifest_path = tmp.path().join("manifest.bin");
        let m = GoldenManifest {
            schema_version: GOLDEN_SCHEMA_VERSION,
            entries: vec![],
        };
        std::fs::write(&manifest_path, bincode::serialize(&m).unwrap()).unwrap();

        let cfg = GoldenConfig {
            bucket: "unused".to_string(),
            manifest: ManifestSource::LocalPath(manifest_path),
        };
        let client = S3Client::new(crate::s3::S3Config::default());

        let (inodes, blobs) = load_golden(&cfg, &client).unwrap();
        assert!(inodes.is_empty());
        assert!(blobs.is_empty());
    }

    #[test]
    fn load_rejects_schema_version_mismatch() {
        let tmp = tempfile::tempdir().unwrap();
        let manifest_path = tmp.path().join("manifest.bin");
        let m = GoldenManifest {
            schema_version: 999, // not GOLDEN_SCHEMA_VERSION
            entries: vec![],
        };
        std::fs::write(&manifest_path, bincode::serialize(&m).unwrap()).unwrap();

        let cfg = GoldenConfig {
            bucket: "unused".to_string(),
            manifest: ManifestSource::LocalPath(manifest_path),
        };
        let client = S3Client::new(crate::s3::S3Config::default());

        let err = load_golden(&cfg, &client).unwrap_err();
        assert_eq!(err.kind(), io::ErrorKind::InvalidData);
        assert!(err.to_string().contains("schema_version"));
    }

    #[test]
    fn load_rejects_corrupt_manifest() {
        let tmp = tempfile::tempdir().unwrap();
        let manifest_path = tmp.path().join("manifest.bin");
        std::fs::write(&manifest_path, b"not a valid bincode payload").unwrap();

        let cfg = GoldenConfig {
            bucket: "unused".to_string(),
            manifest: ManifestSource::LocalPath(manifest_path),
        };
        let client = S3Client::new(crate::s3::S3Config::default());

        let err = load_golden(&cfg, &client).unwrap_err();
        assert_eq!(err.kind(), io::ErrorKind::InvalidData);
    }

    #[test]
    fn load_missing_manifest_fails() {
        let cfg = GoldenConfig {
            bucket: "unused".to_string(),
            manifest: ManifestSource::LocalPath(PathBuf::from("/nonexistent/manifest.bin")),
        };
        let client = S3Client::new(crate::s3::S3Config::default());

        let err = load_golden(&cfg, &client).unwrap_err();
        assert_eq!(err.kind(), io::ErrorKind::NotFound);
    }

    /// Dedup correctness: multiple manifest entries sharing a hash
    /// collapse to one entry in the unique-hash list before par_iter.
    /// We can't cheaply observe "exactly one GET issued" without a
    /// mock S3, but the unique-hash list drives the GET count 1:1,
    /// so testing that list is sufficient.
    #[test]
    fn dedup_collapses_shared_hashes() {
        let entries = vec![
            entry("a.txt", Some("shared-hash"), libc::S_IFREG as u32 | 0o644),
            entry("b.txt", Some("shared-hash"), libc::S_IFREG as u32 | 0o644),
            entry("etc", None, libc::S_IFDIR as u32 | 0o755),
        ];
        let mut hashes: Vec<String> = entries.iter().filter_map(|e| e.hash.clone()).collect();
        hashes.sort();
        hashes.dedup();
        assert_eq!(hashes, vec!["shared-hash".to_string()]);
    }
}
